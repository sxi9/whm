defineOp('stats.goaccess.run', {
  description: 'Render the GoAccess HTML report and a JSON summary of one domain\'s access logs into <home>/.keel/stats as the account (nice/ionice, 120 s)',
  timeoutMs: 180_000,
  schema: z.object({ username: arg.username, domain: arg.domain, logFiles: z.array(arg.absPath).min(1).max(4).optional() }).strict(),
  run: async ({ username, domain, logFiles }, ctx) => {
    const bin = resolveBinary('goaccess');
    if (!bin) throw new OpError('capability_missing', 'goaccess is not installed on this server', { packages: GOACCESS_PACKAGES });
    const info = assertManaged(username);
    const home = path.resolve(info.home);
    const logDir = path.join(DOMLOGS_ROOT, username);
    const candidates = (logFiles || domainLogFiles(username, domain)).map((p) => {
      const resolved = ctx.assertAllowedPath(p, 'read');
      if (path.dirname(resolved) !== logDir || !path.basename(resolved).startsWith(`${domain}-`)) throw new OpError('path_not_allowed', `${p} is not an access log of ${domain} under ${logDir}`);
      return resolved;
    });
    const logs = candidates.filter((p) => { const st = lstatOrNull(p); return Boolean(st?.isFile()) && st.size > 0; });
    const out = goaccessOutputs(home, domain);
    if (!logs.length) return { domain, username, skipped: true, reason: 'no_log', logFiles: candidates, html: out.html, summary: out.summary };
    const tool = requireAsUser();
    const dir = accountPath(username, out.dir, ctx, 'write').target;
    const runAs = (program, argv, opts) => {
      const [exe, args] = asUserArgv(info, program, argv, { tool, nice: opts.nice && hasBinary('nice') });
      const [wrapped, wrappedArgs] = opts.nice ? ioniceArgv(exe, args) : [exe, args];
      return exec(wrapped, wrappedArgs, { timeoutMs: opts.timeoutMs, maxBuffer: opts.maxBuffer, stdinFd: opts.stdinFd, allowFailure: true, env: { HOME: info.home, USER: info.username, LOGNAME: info.username } });
    };
    const keel = await runAs('mkdir', ['-p', '-m', '0711', '--', path.dirname(dir)], { timeoutMs: 30_000 });
    if (keel.code !== 0) throw failureOf(keel, `create ${path.relative(home, path.dirname(dir))}`);
    const made = await runAs('mkdir', ['-p', '-m', '0750', '--', dir], { timeoutMs: 30_000 });
    if (made.code !== 0) throw failureOf(made, `create ${path.relative(home, dir)}`);
    // The report is rendered beside its final name and renamed into place, so
    // the panel never serves a half-written file (goaccess insists on a
    // .html/.json/.csv extension for its output file, so the staging name keeps it).
    const staging = goaccessStaging(out.html);
    const dropStaging = () => runAs('rm', ['-f', '--', staging.html, staging.json], { timeoutMs: 30_000 }).catch(() => {});
    // The domlogs live under /var/log/whm, which the account cannot traverse
    // (0750 whmpanel), so root opens the log — merged in time order when a
    // domain has both the plain and the TLS log — and goaccess, running as the
    // account, reads it from stdin (`-`); nothing under /var/log is opened by
    // the account and nothing in the home is opened by root.
    ctx.assertAllowedPath(GOACCESS_SCRATCH, 'write');
    const scratch = fs.mkdtempSync(path.join(ensurePrivateDir(GOACCESS_SCRATCH), 'goaccess-'));
    let fd = null;
    let run;
    try {
      const source = logs.length === 1 ? logs[0] : (await mergeAccessLogs(logs, path.join(scratch, 'access.log'))).dest;
      fd = fs.openSync(source, fs.constants.O_RDONLY | fs.constants.O_NOFOLLOW);
      run = await runAs(bin, goaccessArgv(['-'], staging.html, staging.json), { nice: true, timeoutMs: 120_000, maxBuffer: 256 * MiB, stdinFd: fd });
    } finally {
      if (fd !== null) fs.closeSync(fd);
      fs.rmSync(scratch, { recursive: true, force: true });
    }
    if (run.code !== 0) { await dropStaging(); throw failureOf(run, `goaccess for ${domain}`); }
    // The JSON report is read back as the account (root never opens files in the home) and dropped.
    const json = await runAs('cat', ['--', staging.json], { timeoutMs: 60_000, maxBuffer: 256 * MiB });
    let report;
    try { if (json.code !== 0) throw new Error(json.stderr); report = JSON.parse(json.stdout); } catch { await dropStaging(); throw new OpError('command_failed', `goaccess for ${domain} produced no JSON report`, { stderr: run.stderr.slice(-4000) }); }
    await runAs('rm', ['-f', '--', staging.json], { timeoutMs: 30_000 }).catch(() => {});
    const moved = await runAs('mv', ['-f', '-T', '--', staging.html, out.html], { timeoutMs: 30_000 });
    if (moved.code !== 0) throw failureOf(moved, `replace ${path.relative(home, out.html)}`);
    const summary = summarizeGoaccess(report, { domain, logFiles: logs });
    await stagedWrite(info, home, out.summary, JSON.stringify(summary), '0640');
    return { domain, username, skipped: false, logFiles: logs, html: out.html, summary: out.summary, generatedAt: summary.generatedAt, totals: summary.totals };
  },
});

defineOp('stats.remove_config', {
  description: 'Remove the generated AWStats configuration of a domain',
  destructive: true,
  schema: z.object({ domain: arg.domain }).strict(),
  run: async ({ domain }, ctx) => {
    const confPath = ctx.assertAllowedPath(path.join(AWSTATS_CONF_DIR, `awstats.${domain}.conf`), 'write');
    const existed = fs.existsSync(confPath);
    if (existed) fs.rmSync(confPath, { force: true });
    return { domain, removed: existed, path: confPath, awstatsInstalled: hasBinary('awstats.pl') || Boolean(detectGenerators().awstats.bin) };
  },
});
