const ARCHIVE_NAME = /^(?!\.)[A-Za-z0-9._-]{1,200}\.(tar\.gz|tgz|tar)$/;
const ROOT_PREFIX = 'homedir';

export function restorableBackups(rows) {
  return (rows || []).filter((r) => r.status === 'done' && r.local_present);
}

export function backupOptionLabel(r) {
  return `${r.name || `#${r.id}`} · ${kindLabel(r.kind)} · ${formatDate(r.created_at)}`;
}

// Paths the restore API takes are relative to the archive's home directory.
export function relativeToHome(archivePath) {
  return String(archivePath || '').replace(/^homedir\//, '');
}

// The server's restore gate (panel-backup.restore / panel-files.sshWriteAllowed):
// .ssh comes back only for a session login of an account with shell access
// and the ssh feature, never while an admin acts as the account. The dialog
// mirrors it so the box is never offered; the server's 403 stays the backstop.
export const SSH_NOTE = 'SSH keys are managed under Security › SSH keys and are not restored here';
export function sshRestoreAllowed(me) {
  if (!me?.account) return false;
  const features = me.account.features ?? me.features ?? {};
  if (features.ssh === false) return false;
  if (!me.account.plan?.has_shell) return false;
  if (me.actingAs) return false;
  return true;
}
// Whether an archive path names .ssh, something under it, or the whole home (which contains it).
export function touchesSsh(archivePath) {
  const rel = relativeToHome(archivePath).replace(/\/+$/, '');
  return rel === '' || rel === '.' || rel === ROOT_PREFIX || rel.split('/')[0] === '.ssh';
}
export function restorablePaths(paths, allowSsh) {
  return allowSsh ? paths : paths.filter((p) => !touchesSsh(p));
}
const insideSsh = (archivePath) => relativeToHome(archivePath).split('/')[0] === '.ssh';

export function restoreSummary(summary) {
  if (!summary || typeof summary !== 'object') return '—';
  const parts = [];
  if (summary.restored != null) parts.push(`${summary.restored} restored`);
  if (summary.skipped != null) parts.push(`${summary.skipped} skipped`);
  if (summary.paths != null) parts.push(`${summary.paths} path${summary.paths === 1 ? '' : 's'}`);
  if (!parts.length) return Object.entries(summary).slice(0, 3).map(([k, v]) => `${k}: ${typeof v === 'object' ? JSON.stringify(v) : v}`).join(', ') || '—';
  return parts.join(', ');
}

function UploadCard({ disabled, onUploaded }) {
  const toast = useToast();
  const [file, setFile] = useState(null);
  const [progress, setProgress] = useState(null);
  const [error, setError] = useState(null);
  const abort = useRef(null);
  const inputRef = useRef(null);
  const validName = file ? ARCHIVE_NAME.test(file.name) : true;

  const start = async () => {
    if (!file) return;
    abort.current = new AbortController();
    setError(null); setProgress({ received: 0, size: file.size });
    try {
      const archive = await uploadArchive(file, { onProgress: (received, size) => setProgress({ received, size }), signal: abort.current.signal });
      toast.success(`${archive.name} uploaded and verified`);
      setFile(null); if (inputRef.current) inputRef.current.value = '';
      onUploaded?.(archive);
    } catch (err) {
      if (err.code !== 'cancelled') setError(err);
    } finally { setProgress(null); abort.current = null; }
  };

  const percent = progress ? percentOf(progress.received, progress.size) : null;
  return (
    <Card title="Upload an archive" subtitle="A backup downloaded from this panel earlier. It is verified and listed as a restore source.">
      <PanelCapabilityState error={isCapabilityError(error) ? error : null} />
      <RequestError error={error} />
      {error?.code === 'wrong_account' && <p className="muted small">Only archives generated for this account can be restored here.</p>}
      <Field label="Archive file" help="A .tar.gz, .tgz or .tar archive generated by this panel; letters, digits, dots, dashes and underscores in the name" error={file && !validName ? ['Rename the file so it only contains letters, digits, ".", "_" or "-" and ends in .tar.gz, .tgz or .tar'] : null} htmlFor="restore-upload">
        {/* The native control is hidden; the kit button opens it and the chosen name is shown beside it. */}
        <input id="restore-upload" ref={inputRef} type="file" hidden accept=".tar.gz,.tgz,.tar,application/gzip,application/x-tar" disabled={disabled || Boolean(progress)} onChange={(e) => { setFile(e.target.files?.[0] || null); setError(null); }} />
        <div style={{ display: 'flex', alignItems: 'center', gap: 10, flexWrap: 'wrap' }}>
          <Button icon={FolderOpen} disabled={disabled || Boolean(progress)} onClick={() => inputRef.current?.click()}>{file ? 'Choose another archive' : 'Choose an archive'}</Button>
          {file ? <span className="muted small">{file.name} · {sizeText(file.size)}</span> : <span className="muted small">No archive chosen yet</span>}
        </div>
      </Field>
      {progress && (
        <div>
          <div className="meter"><span style={{ width: `${percent ?? 0}%` }} /></div>
          <p className="muted small">{sizeText(progress.received)} of {sizeText(progress.size)} sent{progress.received >= progress.size ? ' · verifying the archive' : ''}</p>
        </div>
      )}
      <FormActions>
        <Button variant="primary" icon={Upload} loading={Boolean(progress)} disabled={disabled || !file || !validName || Boolean(progress)} onClick={start}>Upload archive</Button>
        {progress && <Button icon={X} onClick={() => abort.current?.abort()}>Cancel</Button>}
      </FormActions>
    </Card>
  );
}

export default function Restore({ fn }) {
  const toast = useToast();
  const confirm = useConfirm();
  const { me } = usePanelMe();
  const [params, setParams] = useSearchParams();
  const backups = usePanelApi('/backups?page=1&pageSize=200');
  const restores = usePanelApi('/backups/restores');
  const [prefix, setPrefix] = useState(ROOT_PREFIX);
  const [selected, setSelected] = useState([]);
  const [overwrite, setOverwrite] = useState(false);
  const [busy, setBusy] = useState(false);
  const [restoreError, setRestoreError] = useState(null);
  const [job, setJob] = useState(null);
  const selectedId = params.get('backup') || '';
  const options = useMemo(() => restorableBackups(backups.data), [backups.data]);
  const current = options.find((r) => String(r.id) === selectedId) || null;
  const browse = usePanelApi(current ? `/backups/${current.id}/browse?prefix=${encodeURIComponent(prefix)}` : null, { enabled: Boolean(current) });
  const actingAs = me?.actingAs;
  const capability = isCapabilityError(backups.error);
  const allowSsh = sshRestoreAllowed(me);
  const restorable = restorablePaths(selected, allowSsh);

  useEffect(() => { setPrefix(ROOT_PREFIX); setSelected([]); }, [selectedId]);

  if (isFeatureDisabled(backups.error)) return <PanelPage fn={fn}><FeatureDisabledState fn={fn} /></PanelPage>;

  const choose = (id) => setParams(id ? { backup: id } : {}, { replace: true });
  const entries = browse.data?.entries || [];
  const crumbs = prefixCrumbs(prefix);
  const selectableRow = (r) => allowSsh || !touchesSsh(r.path);
  const sshBlocked = !allowSsh && Boolean(current) && (insideSsh(prefix) || entries.some((r) => insideSsh(r.path)));

  const runRestore = async () => {
    if (!current || !restorable.length) return;
    const ok = await confirm({
      title: `Restore ${restorable.length} item${restorable.length === 1 ? '' : 's'} from ${current.name}?`,
      message: overwrite ? 'Files that exist on the account with the same names are replaced by the copies in the archive.' : 'Files that already exist on the account are kept; only missing files are put back.',
      confirmLabel: 'Restore', danger: overwrite,
    });
    if (!ok) return;
    setBusy(true); setRestoreError(null);
    try {
      const { data: res } = await panelApi.post(`/backups/${current.id}/restore`, { paths: restorable.map(relativeToHome), overwrite });
      setJob(res.job.id);
      setSelected([]);
      toast.info('Restore started');
    } catch (err) { setRestoreError(err); } finally { setBusy(false); }
  };

  const finished = (event) => {
    if (event.type === 'done') toast.success('Files restored');
    else if (event.type === 'failed') toast.error(event.error || 'The restore failed');
    restores.refetch();
  };

  return (
    <PanelPage fn={fn} actions={<Button icon={RefreshCw} onClick={() => { backups.refetch(); restores.refetch(); if (current) browse.refetch(); }}>Refresh</Button>}>
      <ImpersonationNotice actingAs={actingAs}>Restores and uploads are only started by the account user; browsing archives works.</ImpersonationNotice>
      <PanelCapabilityState error={capability ? backups.error : null} onRetry={backups.refetch} />
      <div className="grid-2">
        <Card title="Restore from a backup" subtitle="Pick an archive, walk into it and choose what to put back.">
          <Field label="Archive" htmlFor="restore-source" help={options.length ? `${options.length} archive${options.length === 1 ? '' : 's'} can be restored from` : 'Generate or upload a backup first'}>
            <Select id="restore-source" value={selectedId} onChange={choose} placeholder={options.length ? 'Choose an archive' : 'No archives yet'} options={options.map((r) => ({ value: String(r.id), label: backupOptionLabel(r) }))} disabled={!options.length} />
          </Field>
          {current && (
            <Field label="Options">
              <Toggle checked={overwrite} onChange={setOverwrite} label="Replace existing files" description="Off: only files missing from the account are restored. On: the archive's copy wins." disabled={Boolean(actingAs)} />
            </Field>
          )}
          <RequestError error={restoreError} />
          <FormActions>
            <Button variant="primary" icon={RotateCcw} loading={busy} disabled={busy || !current || !restorable.length || Boolean(actingAs)} onClick={runRestore}>Restore {restorable.length ? `${restorable.length} selected` : 'selected'}</Button>
            {!current && <Link className="btn" to="/panel/backups/backups">Generate a backup</Link>}
          </FormActions>
          {job && (
            <div style={{ marginTop: 14 }}>
              <ProgressLog jobId={job} onFinished={finished} />
              <FormActions><Button size="sm" onClick={() => setJob(null)}>Hide progress</Button></FormActions>
            </div>
          )}
        </Card>
        <UploadCard disabled={Boolean(actingAs) || capability} onUploaded={(archive) => { backups.refetch(); choose(String(archive.id)); }} />
      </div>

      <Card title={current ? `Inside ${current.name}` : 'Archive contents'} padded={false}
        actions={current && (
          <nav className="breadcrumbs" aria-label="Archive path">
            <button className="btn btn-sm btn-ghost" onClick={() => setPrefix(ROOT_PREFIX)}><FolderOpen size={14} /> home</button>
            {crumbs.slice(1).map((c) => <span key={c.prefix}><span>›</span> <button className="btn btn-sm btn-ghost" onClick={() => setPrefix(c.prefix)}>{c.name}</button></span>)}
          </nav>
        )}>
        {!current && (
          <div className="card-body"><EmptyState icon={FolderOpen} title="Choose an archive to browse"><p>The folders and files inside it appear here. Tick what you want back and press Restore.</p>{!options.length && <p className="muted">Nothing to pick from yet: <Link to="/panel/backups/backups">generate a backup</Link> or upload one.</p>}</EmptyState></div>
        )}
        {current && isCapabilityError(browse.error) && <div className="card-body"><PanelCapabilityState error={browse.error} onRetry={browse.refetch} /></div>}
        {current && (
          <DataTable
            columns={[
              { key: 'name', label: 'Name', render: (r) => <>{r.type === 'dir' ? <button className="btn btn-sm btn-ghost" onClick={() => setPrefix(r.path)}><FolderOpen size={14} /> {r.name}</button> : <code>{r.name}</code>}{!selectableRow(r) && <span className="muted small"> · managed under Security › SSH keys</span>}</>},
              { key: 'type', label: 'Type', render: (r) => ({ dir: 'Folder', file: 'File', symlink: 'Link' }[r.type] || r.type) },
              { key: 'files', label: 'Files', align: 'right', render: (r) => (r.type === 'dir' ? r.files : <span className="muted">—</span>) },
              { key: 'size', label: 'Size', align: 'right', render: (r) => sizeText(r.size) },
              { key: 'mtime', label: 'Modified', render: (r) => (r.mtime ? formatDate(r.mtime) : <span className="muted">—</span>) },
            ]}
            rows={entries} loading={browse.loading} error={isCapabilityError(browse.error) ? null : browse.error} rowKey={(r) => r.path}
            selectable selected={selected} onSelectedChange={(keys) => setSelected(restorablePaths(keys, allowSsh))} canSelect={selectableRow} dense
            emptyText={browse.loading ? 'Reading the archive…' : 'This folder is empty in the archive.'}
          />
        )}
        {sshBlocked && <div className="card-body muted small" data-testid="ssh-note"><Info size={12} /> {SSH_NOTE}.</div>}
        {current && browse.data?.truncated && <div className="card-body muted small">Only the first {entries.length} entries of this folder are shown.</div>}
        {current && selected.length > 0 && <div className="card-body muted small">{selected.length} selected: {selected.slice(0, 6).map((p) => <code key={p}>{relativeToHome(p)}</code>).reduce((acc, el, i) => (i ? [...acc, ' ', el] : [el]), [])}{selected.length > 6 ? ' …' : ''}</div>}
      </Card>

      <Card title="Restore history" subtitle="Restores started from this panel." padded={false}>
        <DataTable
          columns={[
            { key: 'id', label: 'Restore', render: (r) => `#${r.id}` },
            { key: 'backup_id', label: 'Archive', render: (r) => { const b = (backups.data || []).find((x) => x.id === r.backup_id); return b ? <code>{b.name}</code> : `#${r.backup_id}`; } },
            { key: 'kind', label: 'Scope', render: (r) => ({ files: 'Selected files', account: 'Whole account' }[r.kind] || r.kind) },
            { key: 'options', label: 'Items', align: 'right', render: (r) => (Array.isArray(r.options?.paths) ? r.options.paths.length : <span className="muted">—</span>) },
            { key: 'status', label: 'Status', render: (r) => <StatusPill status={statusTone(r.status)}>{r.status}</StatusPill> },
            { key: 'summary', label: 'Result', render: (r) => (r.error ? <span className="muted">{r.error}</span> : restoreSummary(r.summary)) },
            { key: 'created_at', label: 'Started', render: (r) => formatDate(r.created_at) },
            { key: 'finished_at', label: 'Finished', render: (r) => (r.finished_at ? formatDate(r.finished_at) : <span className="muted">—</span>) },
          ]}
          rows={restores.data || []} loading={restores.loading} error={isCapabilityError(restores.error) || isFeatureDisabled(restores.error) ? null : restores.error} rowKey={(r) => r.id} dense
          emptyText="No restores yet. Each restore you start appears here with its outcome."
        />
      </Card>
      <p className="muted small"><Info size={12} /> Restores put files back under your home directory as your own user; databases and mail are restored by your hosting provider on request.</p>
    </PanelPage>
  );
}
