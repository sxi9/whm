describe('cross-category helpers', () => {
  beforeAll(() => provision(true));

  it('sends notifications, installs/removes DKIM keys and applies routing', async () => {
    const sent = await app.ctx.mail.sendNotification({ to: ['root@example.com'], subject: 'Backup finished', text: 'All good' });
    expect(sent.accepted).toBe(true);
    expect(app.agent.callsTo('mail.sendmail').at(-1).args).toMatchObject({ from: 'whm@mail.example.com', to: ['root@example.com'], subject: 'Backup finished' });
    const dkim = await app.ctx.mail.installDkimKey('example.com', { selector: 'default', privateKeyPem: '-----BEGIN PRIVATE KEY-----\nx\n-----END PRIVATE KEY-----' });
    expect(dkim).toMatchObject({ installed: true, path: '/etc/exim4/whm/dkim/example.com.key' });
    expect((await app.ctx.mail.removeDkimKey('example.com')).removed).toBe(2);
    const routing = await app.ctx.mail.setRouting('example.com', 'remote');
    expect(routing).toMatchObject({ domain: 'example.com', routing: 'remote', applied: true, hooked: true });
    expect(app.ctx.db.prepare("SELECT routing FROM mail_domains WHERE domain = 'example.com'").get().routing).toBe('remote');
    const local = app.agent.callsTo('mail.config.include.write').filter((c) => c.args.name === 'local_domains.lst').at(-1).args.content;
    expect(local).not.toContain('example.com');
    // The relay list write wires the main-section hook so Exim's domain lists read the files.
    const relay = app.agent.callsTo('mail.config.include.write').filter((c) => c.args.name === 'relay_domains.lst').at(-1).args;
    expect(relay).toMatchObject({ hook: true, reload: true });
    expect(relay.sqliteDbfile).toBeUndefined();
    const backup = await app.ctx.mail.setRouting('example.com', 'backup');
    expect(backup.applied).toBe(true);
    expect(app.agent.callsTo('mail.config.include.write').filter((c) => c.args.name === 'relay_domains.lst').at(-1).args.content).toContain('\nexample.com\n');
    // Written but not read by Exim is not "applied".
    app.agent.set('mail.config.include.write', (args) => ({ ...INCLUDE_WRITE(args), domainListsHooked: args.hook ? false : null, domainListsDetail: "Exim's local_domains list does not read the panel's domain list file", hint: args.hook ? 'remove any definition of those macros elsewhere' : null }));
    await expect(app.ctx.mail.setRouting('example.com', 'local')).rejects.toMatchObject({ status: 409, code: 'routing_not_applied', applied: false, hooked: false, hint: 'remove any definition of those macros elsewhere', message: expect.stringMatching(/does not read the panel's domain lists.*remove any definition/) });
    expect(app.ctx.db.prepare("SELECT routing FROM mail_domains WHERE domain = 'example.com'").get().routing).toBe('local');
    app.agent.set('mail.config.include.write', INCLUDE_WRITE);
    await provision(false);
    expect(await app.ctx.mail.installDkimKey('example.com', { selector: 'default', privateKeyPem: 'x' })).toMatchObject({ installed: false });
    expect(await app.ctx.mail.setRouting('example.com', 'local')).toMatchObject({ applied: false, hooked: null });
  });
});

describe('pure helpers', () => {
  it('parses CIDR lists and validates networks', () => {
    expect(isCidr('10.0.0.0/8')).toBe(true);
    expect(isCidr('10.0.0.0/33')).toBe(false);
    expect(isCidr('2001:db8::/32')).toBe(true);
    expect(isCidr('example.com')).toBe(false);
    expect(parseCidrList('1.2.3.0/24 # a\n;comment\n1.2.3.0/24\n4.5.6.7,extra\nbad')).toEqual({ cidrs: ['1.2.3.0/24', '4.5.6.7'], invalid: ['bad'], invalidCount: 1 });
  });

  it('renders an ACL with only the enabled sections', () => {
    const none = renderAcl({ dir: 'etc/exim4/whm', country: { blockCount: 0, allowCount: 0, message: 'x' }, domain: { blockCount: 0, allowCount: 0, message: 'x' }, greylist: { enabled: false } });
    expect(none).toContain('# No filters are enabled.');
    const some = renderAcl({ dir: 'etc/exim4/whm', country: { blockCount: 1, allowCount: 1, message: 'Country blocked' }, domain: { blockCount: 1, allowCount: 0, message: 'Domain blocked' }, greylist: { enabled: true, backend: 'sqlite', initialDelayMinutes: 5, mustRetryHours: 4, message: 'Greylisted' } });
    expect(some).toContain('deny    !authenticated = *\n        hosts = /etc/exim4/whm/country_blocklist.lst\n        message = Country blocked');
    // IPv6 loopback needs a non-colon list separator; the leading empty item matches local submissions.
    expect(some).toContain('!hosts = <; ; 127.0.0.1 ; ::1 ; /etc/exim4/whm/country_allowlist.lst');
    expect(some).toContain('warn    hosts = <; ; 127.0.0.1 ; ::1 ; /etc/exim4/whm/greylist_trusted_hosts.lst');
    expect(some).not.toMatch(/hosts = : /);
    expect(some).not.toContain('domain_allowlist');
    expect(some).toContain('>= 300 AND (${tod_epoch} - first_seen) <= 14400');
    expect(some).toContain('defer   condition = ${if or{{eq{$acl_m_whmgrey}{new}}');
    // Legacy form (dbfileOption false) keeps the path inside the query.
    expect(some).toContain('${lookup sqlite {/var/lib/whm/greylist/greylist.db SELECT CASE');
    const taintSafe = renderAcl({ dir: 'etc/exim4/whm', country: { blockCount: 0, allowCount: 0, message: 'x' }, domain: { blockCount: 0, allowCount: 0, message: 'x' }, greylist: { enabled: true, backend: 'sqlite', dbfileOption: true, initialDelayMinutes: 5, mustRetryHours: 4, message: 'Greylisted' } });
    expect(taintSafe).not.toContain('lookup sqlite {/var/lib/whm/greylist/greylist.db');
    expect(taintSafe).toContain('${lookup sqlite {SELECT CASE WHEN passed = 1');
    expect(taintSafe).toContain('${lookup sqlite {INSERT OR IGNORE INTO greylist');
    expect(taintSafe).toContain('sqlite_dbfile = /var/lib/whm/greylist/greylist.db');
  });
});
